import { Empty } from '../components/ui'

/**
 * Заглушка раздела, закрытого правами роли.
 *
 * Без неё экран показывал обычное пустое состояние — «Всё под
 * контролем», «На вас нет открытых задач». Для человека, которому просто
 * не выдали право, это прямая неправда: он видел бодрый отчёт о полном
 * порядке вместо сообщения, что данные ему не показывают.
 */
export function NoAccess({ what = 'Этот раздел' }: { what?: string }) {
  return (
    <div className="page">
      <Empty
        icon="lock"
        title="Раздел закрыт"
        text={`${what} недоступен для вашей роли. Если доступ нужен — попросите администратора выдать право «Просмотр задач».`}
      />
    </div>
  )
}
