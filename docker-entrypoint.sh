#!/bin/sh
#
# Подготовка базы перед запуском.
#
# База лежит на подключённом томе и переживает пересборку образа, поэтому
# миграции применяются при каждом старте, а не при сборке: в момент сборки
# нужного файла ещё не существует.
#
set -e

echo "== Миграции =="
npx prisma migrate deploy

echo "== Запуск =="
exec "$@"
